    func testPlainAndRTFSameItemRoundTrip() throws {
        let text = "Hello rich"
        let plain = Data(text.utf8)
        let rtf = Data("{\\rtf1\\ansi \(text)}".utf8)
        let item = NSPasteboardItem()
        item.setData(plain, forType: NSPasteboard.PasteboardType(ClipboardTypeIdentifiers.utf8PlainText))
        item.setData(rtf, forType: NSPasteboard.PasteboardType(ClipboardTypeIdentifiers.rtf))
        let pb = uniquePasteboard()
        pb.clearContents()
        XCTAssertTrue(pb.writeObjects([item]))

        let parser = PasteboardParser()
        guard let parsed = parser.parse(pasteboard: pb) else {
            return XCTFail("parse")
        }
        let types = Set(parsed.representations.map(\.typeIdentifier))
        XCTAssertTrue(types.contains(ClipboardTypeIdentifiers.utf8PlainText) || types.contains(ClipboardTypeIdentifiers.plainText))
        XCTAssertTrue(types.contains(ClipboardTypeIdentifiers.rtf))
        XCTAssertTrue(parsed.representations.allSatisfy { $0.itemIndex == 0 })

        let store = InMemoryPayloadStore()
        let engine = ClipboardEngine(repository: InMemoryClipboardRepository(), payloadStore: store)
        guard case .inserted(let entry) = engine.ingest(parsed: parsed) else {
            return XCTFail("insert")
        }
        let dest = uniquePasteboard()
        XCTAssertEqual(try engine.paste(entry: entry, pasteboard: dest), 1)
        let destItem = dest.pasteboardItems?.first
        XCTAssertNotNil(destItem?.data(forType: NSPasteboard.PasteboardType(ClipboardTypeIdentifiers.rtf)))
        let plainOut = destItem?.data(forType: NSPasteboard.PasteboardType(ClipboardTypeIdentifiers.utf8PlainText))
            ?? destItem?.data(forType: .string)
        XCTAssertNotNil(plainOut)
    }

    func testOversizedRepresentationSkippedWholeNeverTruncated() throws {
        let cap = 64
        let parser = PasteboardParser(maxRepresentationBytes: cap)
        let over = Data(repeating: 0x41, count: cap + 1)
        let ok = Data("fits".utf8)

        let item = NSPasteboardItem()
        item.setData(over, forType: NSPasteboard.PasteboardType(ClipboardTypeIdentifiers.png))
        item.setData(ok, forType: NSPasteboard.PasteboardType(ClipboardTypeIdentifiers.utf8PlainText))
        let pb = uniquePasteboard()
        pb.clearContents()
        XCTAssertTrue(pb.writeObjects([item]))

        guard let parsed = parser.parse(pasteboard: pb) else {
            return XCTFail("parse should keep under-cap rep")
        }
        XCTAssertFalse(parsed.representations.contains { $0.typeIdentifier == ClipboardTypeIdentifiers.png })
        guard let textRep = parsed.representations.first(where: {
            $0.typeIdentifier == ClipboardTypeIdentifiers.utf8PlainText
                || $0.typeIdentifier == ClipboardTypeIdentifiers.plainText
        }) else {
            return XCTFail("plain text should remain")
        }
        XCTAssertEqual(textRep.data, ok)
        // Ensure we never stored a truncated PNG of length == cap under the PNG UTI.
        XCTAssertFalse(parsed.representations.contains {
            $0.typeIdentifier == ClipboardTypeIdentifiers.png && $0.data.count == cap
        })
    }

    func testSelfWriteIgnoredOnceThenExternalIdenticalCopyCaptured() throws {
        let store = InMemoryPayloadStore()
        let repo = InMemoryClipboardRepository()
        let engine = ClipboardEngine(repository: repo, payloadStore: store)
        let pb = uniquePasteboard()

        let textData = Data("identical-content".utf8)
        let typeID = ClipboardTypeIdentifiers.utf8PlainText
        let parsed = ParsedPasteboardItem(
            representations: [
                ParsedRepresentation(itemIndex: 0, typeIdentifier: typeID, data: textData)
            ],
            primaryKind: .plainText,
            previewText: "identical-content",
            searchText: "identical-content",
            fingerprint: Fingerprinter.fingerprint(typeIdentifier: typeID, data: textData)
        )
        guard case .inserted(let entry) = engine.ingest(parsed: parsed) else {
            return XCTFail("insert")
        }

        XCTAssertEqual(try engine.paste(entry: entry, pasteboard: pb), 1)
        XCTAssertEqual(engine.capture(from: pb), .ignoredSelfWrite)

        // External copy of the same content (new change count) must not be suppressed.
        // Re-write via a separate pasteboard write to bump change count.
        let external = NSPasteboardItem()
        external.setData(textData, forType: NSPasteboard.PasteboardType(typeID))
        pb.clearContents()
        XCTAssertTrue(pb.writeObjects([external]))

        let result = engine.capture(from: pb)
        guard case .updatedExisting(let updated) = result else {
            return XCTFail("expected dedupe update after external identical copy, got \(result)")
        }
        XCTAssertEqual(updated.id, entry.id)
        XCTAssertEqual(try repo.allEntries().count, 1)
    }

