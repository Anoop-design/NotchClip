    func testTwoFilePasteboardRoundTrip() throws {
        let tmp = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString, isDirectory: true)
        try FileManager.default.createDirectory(at: tmp, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: tmp) }

        let fileA = tmp.appendingPathComponent("a.txt")
        let fileB = tmp.appendingPathComponent("b.txt")
        let contentA = Data("file-a-bytes".utf8)
        let contentB = Data("file-b-bytes".utf8)
        try contentA.write(to: fileA)
        try contentB.write(to: fileB)

        let sourcePB = uniquePasteboard()
        let itemA = NSPasteboardItem()
        itemA.setString(fileA.absoluteString, forType: .fileURL)
        let itemB = NSPasteboardItem()
        itemB.setString(fileB.absoluteString, forType: .fileURL)
        sourcePB.clearContents()
        XCTAssertTrue(sourcePB.writeObjects([itemA, itemB]))
        XCTAssertEqual(sourcePB.pasteboardItems?.count, 2)

        let storeDir = tmp.appendingPathComponent("payloads", isDirectory: true)
        let store = try PayloadStore(rootDirectory: storeDir)
        let repo = InMemoryClipboardRepository()
        let engine = ClipboardEngine(repository: repo, payloadStore: store)
        let parser = PasteboardParser()

        guard let parsed = parser.parse(pasteboard: sourcePB) else {
            return XCTFail("parse two files")
        }
        XCTAssertEqual(parsed.primaryKind, .fileList)
        let fileReps = parsed.representations.filter { $0.typeIdentifier == ClipboardTypeIdentifiers.fileURL }
        XCTAssertEqual(fileReps.count, 2)
        XCTAssertEqual(fileReps.map(\.itemIndex), [0, 1])
        XCTAssertEqual(Set(fileReps.compactMap(\.originalFilePath)), Set([fileA.path, fileB.path]))

        // Stored payloads must not contain source file *contents* — only file-url representation bytes.
        guard case .inserted(let entry) = engine.ingest(parsed: parsed) else {
            return XCTFail("insert")
        }
        for ref in entry.payloadRefs {
            let data = try store.loadData(for: ref)
            XCTAssertNotEqual(data, contentA)
            XCTAssertNotEqual(data, contentB)
        }

        let destPB = uniquePasteboard()
        let written = try engine.paste(entry: entry, pasteboard: destPB)
        XCTAssertEqual(written, 2)
        XCTAssertEqual(destPB.pasteboardItems?.count, 2)

        let destItems = destPB.pasteboardItems ?? []
        let destPaths = destItems.compactMap { item -> String? in
            guard let data = item.data(forType: .fileURL) else { return nil }
            return parser.filePath(fromFileURLData: data)
        }
        XCTAssertEqual(destPaths, [fileA.path, fileB.path])
    }

