// MARK: - Failure injection helpers (tests only)

/// Repository that can fail on upsert/remove for reliability tests.
final class FailingClipboardRepository: ClipboardRepository, @unchecked Sendable {
    private let inner = InMemoryClipboardRepository()
    private let lock = NSLock()
    var failOnUpsertCount: Int?
    var failOnRemoveCount: Int?
    private var upserts = 0
    private var removes = 0

    init(failOnUpsertCount: Int? = nil, failOnRemoveCount: Int? = nil) {
        self.failOnUpsertCount = failOnUpsertCount
        self.failOnRemoveCount = failOnRemoveCount
    }

    func allEntries() throws -> [ClipboardEntry] { try inner.allEntries() }
    func entry(id: UUID) throws -> ClipboardEntry? { try inner.entry(id: id) }
    func sortedEntries() throws -> [ClipboardEntry] { try inner.sortedEntries() }
    func search(query: String) throws -> [ClipboardEntry] { try inner.search(query: query) }
    func removeAll() throws { try inner.removeAll() }

    func upsert(_ entry: ClipboardEntry) throws {
        lock.lock()
        upserts += 1
        let n = upserts
        let failAt = failOnUpsertCount
        lock.unlock()
        if let failAt, n == failAt {
            throw ClipboardRepositoryError.persistenceFailed
        }
        try inner.upsert(entry)
    }

    func remove(id: UUID) throws {
        lock.lock()
        removes += 1
        let n = removes
        let failAt = failOnRemoveCount
        lock.unlock()
        if let failAt, n == failAt {
            throw ClipboardRepositoryError.persistenceFailed
        }
        try inner.remove(id: id)
    }
}
