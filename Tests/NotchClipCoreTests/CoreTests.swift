    func testFingerprintIncludesItemIndex() {
        let sameData = Data("x".utf8)
        let oneItem = [
            ParsedRepresentation(itemIndex: 0, typeIdentifier: "public.utf8-plain-text", data: sameData)
        ]
        let twoItems = [
            ParsedRepresentation(itemIndex: 0, typeIdentifier: "public.utf8-plain-text", data: sameData),
            ParsedRepresentation(itemIndex: 1, typeIdentifier: "public.utf8-plain-text", data: sameData)
        ]
        XCTAssertNotEqual(
            Fingerprinter.fingerprint(representations: oneItem),
            Fingerprinter.fingerprint(representations: twoItems)
        )
        // Order of hashing is by item index — deterministic for multi same-UTI
        let swappedInput = [
            ParsedRepresentation(itemIndex: 1, typeIdentifier: "public.utf8-plain-text", data: sameData),
            ParsedRepresentation(itemIndex: 0, typeIdentifier: "public.utf8-plain-text", data: sameData)
        ]
        XCTAssertEqual(
            Fingerprinter.fingerprint(representations: twoItems),
            Fingerprinter.fingerprint(representations: swappedInput)
        )
    }

